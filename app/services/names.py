def _norm(word: str) -> str:
    return word.strip().lower().replace("’", "'").replace("`", "'")


def _cap(word: str) -> str:
    """«петренко-сидоренко» → «Петренко-Сидоренко», великі літери в правильно набраних словах не чіпаємо."""
    if word.islower() or word.isupper():
        return "-".join(p[:1].upper() + p[1:].lower() for p in word.split("-"))
    return word


def split_full_name(full: str) -> tuple[str, str, str]:
    """Повертає (прізвище, ім'я, по батькові)."""
    words = [_cap(w) for w in re.split(r"\s+", (full or "").strip()) if w]
    if not words:
        return "", "", ""
    if len(words) == 1:
        w = words[0]
        if _norm(w) not in FIRST_NAMES and SURNAME.search(_norm(w)) and not PATRONYMIC.search(_norm(w)):
            return w, "", ""
        return "", w, ""

    middle = ""
    rest = []
    for w in words:
        if not middle and PATRONYMIC.search(_norm(w)) and len(words) > 1:
            middle = w
        else:
            rest.append(w)
    if not rest:
        return "", "", middle

    first_idx = next((i for i, w in enumerate(rest) if _norm(w) in FIRST_NAMES), None)
    if first_idx is None and len(rest) >= 2:
        # жодного знайомого імені: якщо перше слово схоже на прізвище, а друге — ні, порядок «Прізвище Ім'я»;
        # якщо навпаки — «Ім'я Прізвище»; інакше як у документах
        s0, s1 = bool(SURNAME.search(_norm(rest[0]))), bool(SURNAME.search(_norm(rest[1])))
        first_idx = 0 if (s1 and not s0) else 1
    if first_idx is None:  # одне слово крім по батькові
        return "", rest[0], middle
    first = rest[first_idx]
    last = " ".join(w for i, w in enumerate(rest) if i != first_idx)
    return last, first, middle


def join_name(last: str, first: str, middle: str) -> str:
    return " ".join(p for p in (last, first, middle) if p)
