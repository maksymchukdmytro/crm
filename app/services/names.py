import re

PATRONYMIC = re.compile(r"(ович|евич|євич|йович|івна|ївна|овна|евна|ічна|инична|ична)$", re.I)
SURNAME = re.compile(
    r"(енко|єнко|чук|щук|ук|юк|ак|як|ик|ко|ський|цький|зький|ська|цька|зька|ов|ев|єв|ін|їн|ова|ева|єва|іна|їна|"
    r"ин|ина|ич|ишин|ишина|ець|ан|яр|ар|ій|ий|ко)$", re.I)

# Найпоширеніші імена (українські й російські написання). Регістр не важливий.
